function generateSlots(facilityId: string, floorsCount: number, slotsPerFloor: number): ParkingSlot[] {
  const slots: ParkingSlot[] = [];
  const types: ('compact' | 'suv' | 'ev' | 'motorcycle' | 'accessible')[] = [
    'compact',
    'compact',
    'suv',
    'suv',
    'ev',
    'ev',
    'accessible',
    'motorcycle',
  ];

  for (let floor = 1; floor <= floorsCount; floor++) {
    for (let i = 1; i <= slotsPerFloor; i++) {
      const typeIndex = (floor * 7 + i * 3) % types.length;
      const vehicleType = types[typeIndex];
      const isEv = vehicleType === 'ev';
      const slotId = `${facilityId}-F${floor}-${String(i).padStart(2, '0')}`;
      const bayLetter = String.fromCharCode(64 + floor);
      const bayCode = `${bayLetter}-${String(i).padStart(2, '0')}`;
      
      // Deterministic but realistic initial occupancy ~55-75%
      const seed = (facilityId.charCodeAt(0) * 17 + floor * 31 + i * 13) % 100;
      const isOccupied = seed < 64;
      const carModel = isOccupied ? CAR_MODELS[(seed + i) % CAR_MODELS.length] : undefined;

      slots.push({
        id: slotId,
        bayCode,
        floor,
        vehicleType,
        isOccupied,
        isReserved: false,
        isEvCharger: isEv,
        chargerSpeedKw: isEv ? (i % 2 === 0 ? 150 : 50) : undefined,
        occupiedCarModel: carModel,
        rateMultiplier: isEv ? 1.2 : 1.0,
      });
    }
  }

  return slots;
}

